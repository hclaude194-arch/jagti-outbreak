"""
Point sources of ambient sound, placed from the campus layout and the outdoor props, written to
Assets/Resources/Audio/ambient_emitters.json for Jagti.Audio.AmbienceDirector:

  water_trickle    along the water channels (every ~22 m)
  flag_flap        at the feather flags (one per cluster)
  transformer_hum  the power substation
  kitchen_fan      the mess kitchen's back wall
  fridge_hum       along the Vipanan shop fronts
  lamp_buzz        street lamps, at night only
  crickets_spot    lawns and shrub borders, from dusk

x, z are map metres; y is the height above the ground there (the runtime samples the terrain).
"""
import json
import math
import os


def along(points, step):
    out = []
    carry = 0.0
    for i in range(0, len(points) - 2, 2):
        x0, z0, x1, z1 = points[i], points[i + 1], points[i + 2], points[i + 3]
        seg = math.hypot(x1 - x0, z1 - z0)
        d = carry
        while d < seg:
            t = d / seg
            out.append((x0 + (x1 - x0) * t, z0 + (z1 - z0) * t))
            d += step
        carry = d - seg
    return out


def thin(points, radius):
    kept = []
    for p in points:
        if all((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 > radius * radius for q in kept):
            kept.append(p)
    return kept


def write(out_dir, root):
    layout = json.load(open(os.path.join(root, "Assets", "Data", "campus_layout.json")))
    props_path = os.path.join(root, "Assets", "Data", "outdoor_props.json")
    props = json.load(open(props_path))["props"] if os.path.exists(props_path) else []
    em = []

    def add(sound, x, z, y=0.5, when="any"):
        em.append({"sound": sound, "x": round(x, 2), "z": round(z, 2), "y": y, "when": when})

    for ch in layout.get("water", []):
        for (x, z) in along(ch["points"], 22.0):
            add("water_trickle", x, z, 0.2)

    flags = [(p["x"], p["z"]) for p in props if p["prop"].startswith("Feather_Flag")]
    for (x, z) in thin(flags, 14.0):
        add("flag_flap", x, z, 2.5)

    for b in layout["buildings"]:
        n = b["name"]
        if n.startswith("Substation"):
            add("transformer_hum", b["x"], b["z"] + b["depth"] / 2 + 8, 1.5)
        if n.endswith("Kitchen"):
            add("kitchen_fan", b["x"] + b["width"] / 2 + 0.5, b["z"], 3.0)
            add("kitchen_fan", b["x"], b["z"] - b["depth"] / 2 - 0.5, 3.0)
        if n.startswith("Vipanan"):
            long_x = b["width"] > b["depth"]
            for k in (-0.3, 0.3):
                if long_x:
                    add("fridge_hum", b["x"] + b["width"] * k, b["z"], 1.0)
                else:
                    add("fridge_hum", b["x"], b["z"] + b["depth"] * k, 1.0)
    for p in layout.get("places", []):
        if p["name"] == "Power Substation":
            add("transformer_hum", p["x"], p["z"], 2.0)

    lamps = [(p["x"], p["z"]) for p in props if p["prop"] in ("Lamp_Post", "Garden_Lamp")]
    for (x, z) in thin(lamps, 30.0):
        add("lamp_buzz", x, z, 4.0, "night")

    lawns = [(p["x"], p["z"]) for p in props if p["prop"] in ("Shrub_Border", "Park_Bench", "Kerbed_Bed")]
    for (x, z) in thin(lawns, 35.0):
        add("crickets_spot", x, z, 0.2, "dusk")

    json.dump({"info": "Generated by tools/audio/emitters.py from campus_layout.json and outdoor_props.json.",
               "emitters": em}, open(os.path.join(out_dir, "ambient_emitters.json"), "w"), indent=0)
    print("[audio] %d ambient emitters" % len(em))
